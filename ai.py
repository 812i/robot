import streamlit as st

st.set_page_config(page_title="Medical Robots Portal", page_icon="⚕️", layout="centered")

st.title("⚕️ الأجهزة والروبوتات المتقدمة في الجراحة والطب")
st.write("مرحباً بكِ في البوابة التفاعلية لاستعراض أبرز التطبيقات الروبوتية الحديثة في القطاع الصحي.")

# قائمة منسدلة لاختيار الروبوت الطبي
robot_choice = st.selectbox(
    "اختر الروبوت الطبي للاستكشاف:",
    [
        "روبوت دافنشي (Da Vinci Surgical System)",
        "روبوت روزا (ROSA Brain & Spine Robot)",
        "روبوت مابور (Mako SmartRobotics)",
        "روبوتات التأهيل والعلاج الطبيعي (Exoskeletons)"
    ]
)

if robot_choice == "روبوت دافنشي (Da Vinci Surgical System)":
    st.subheader("🤖 1. روبوت دافنشي للجراحات الدقيقة")
    st.markdown("""
    * **النوع:** نظام جراحي بمساعدة الحاسوب وعن بُعد (Computer-assisted Surgical System).
    * **طريقة العمل:** يجلس الجراح على وحدة تحكم مرئية ثلاثية الأبعاد (3D HD)، وتترجم وحدة التحكم حركات يديه بدقة متناهية إلى أدوات دقيقة داخل جسم المريض، مع إلغاء أي رجفة طبيعية في يد الإنسان.
    * **الفائدة الطبية:** إجراء عمليات معقدة (مثل جراحات المسالك البولية والقلب والنساء) من خلال شقوق جراحية مجهرية صغرى، مما يقلل النزيف، يسرع الشفاء، ويقلل فترة بقاء المريض بالمستشفى.
    """)

elif robot_choice == "روبوت روزا (ROSA Brain & Spine Robot)":
    st.subheader("🧠 2. روبوت روزا لجراحات المخ والأعصاب والعمود الفقري")
    st.markdown("""
    * **النوع:** مساعد جراحي عصبي ذكي مزود بنظام توجيه بالأشعة.
    * **طريقة العمل:** يعمل كذراع روبوتي يوجه الجراح بدقة مذهلة بناءً على خرائط دماغية ثلاثية الأبعاد مسبقة التصوير للمريض، لتحديد إحداثيات الدقة بدقة تصل لأجزاء من المليمتر.
    * **الفائدة الطبية:** تقليل وقت الجراحة بشكل كبير في العمليات الدقيقة جداً مثل جراحات الصرع وإزالة أورام الدماغ بدقة بالغة ودون الإضرار بالأنسجة السليمة.
    """)

elif robot_choice == "روبوت مابور (Mako SmartRobotics)":
    st.subheader("🦴 3. روبوت ميكو لجراحات العظام المفاصل")
    st.markdown("""
    * **النوع:** ذراع روبوتي تفاعلي متخصص في استبدال المفاصل (الركبة الورك).
    * **طريقة العمل:** يضع الجراح خطة جراحية افتراضية مسبقة لكل مريض، ويقوم الذراع الروبوتي بمساعدة الجراح على إزالة العظام التالفة بدقة مطابقة للخطة المرسومة تماماً مع منع الجراح من تجاوز الحدود الآمنة.
    * **الفائدة الطبية:** تحقيق محاذاة أدق للمفصل الصناعي، تقليل الألم بعد العملية، وزيادة العمر الافتراضي للمفصل المزروع.
    """)

elif robot_choice == "روبوتات التأهيل والعلاج الطبيعي (Exoskeletons)":
    st.subheader("🦿 4. الهياكل الخارجية لتأهيل الأطراف")
    st.markdown("""
    * **النوع:** هيكل روبوتي قابل للارتداء (Wearable Robotic Exoskeleton).
    * **طريقة العمل:** يتم تثبيته على أطراف المريض المصاب بشلل أو ضعف عضلي، وتعمل المستشعرات الذكية على استشعار نية الحركة لدى المريض ومساعدته آلياً على تحريك الساقين أو الذراعين.
    * **الفائدة الطبية:** مساعدة المرضى على استعادة القدرة على المشي، وتحفيز الجهاز العصبي على التعافي السريع أثناء جلسات العلاج الطبيعي.
    """)

st.markdown("---")
st.info("💡 تم تصميم هذا التطبيق لاستعراض مستقبل الروبوتات في إنقاذ الأرواح وتطوير الرعاية الصحية.")
